        private static readonly KeyValuePair<string, string>[] Aliases =
        {
            new KeyValuePair<string, string>("滿洲鄉", "滿州鄉")
        };

        public static IList<string> Of(string city)
        {
            string[] list;
            return ByCity.TryGetValue(TyphoonCities.Normalize(city), out list) ? list : new string[0];
        }

        public static bool IsStandard(string city, string area)
        {
            return Of(city).Contains(TyphoonCities.Normalize(area));
        }

        // 公告的範圍指的是這個縣市的哪幾個區？例如「秀林鄉大天祥地區(含…)」→ 秀林鄉；「桃源區拉芙蘭里」→ 桃源區；
        // 範圍列了好幾個區就全部回傳。找不到（例如某個衛生所、某戶人家）回傳空清單。
        // 長的區名先比，比到的部分就不再給短的比，所以「安南區」不會被當成「南區」
        public static List<string> Match(string city, string scope)
        {
            var found = new List<string>();
            string text = TyphoonCities.Normalize(scope);
            foreach (var alias in Aliases) text = text.Replace(alias.Key, alias.Value);

            foreach (string name in Of(city).OrderByDescending(n => n.Length))
            {
                int at = text.IndexOf(name, StringComparison.Ordinal);
                if (at < 0) continue;
                found.Add(name);
                text = text.Remove(at, name.Length).Insert(at, new string('\u0001', name.Length));   // 蓋掉已經比到的部分
            }
            return found;
        }
